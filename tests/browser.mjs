import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';

const dir=path.resolve('test-results');await mkdir(dir,{recursive:true});
const origin=process.env.TEST_URL||'http://127.0.0.1:5174';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'],downloadsPath:dir});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[],network=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
page.on('request',req=>network.push(req.url()));
try{
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.__PELAGIC__?.diagnostics.time>0.2,{timeout:60000});
  await page.waitForSelector('#loading',{state:'detached',timeout:60000});
  await page.screenshot({path:path.join(dir,'01-sunset.png')});
  assert.equal(await page.locator('#error').isVisible(),false);
  await page.locator('#cycle').uncheck();
  const initial=await page.evaluate(()=>window.__PELAGIC__.diagnostics);
  await page.mouse.move(700,330);await page.mouse.down();await page.mouse.move(850,400,{steps:8});await page.mouse.up();
  const moved=await page.evaluate(()=>window.__PELAGIC__.diagnostics);
  assert.notDeepEqual(initial.camera,moved.camera);
  await page.locator('#reset').click();
  await page.waitForTimeout(800);
  const reset=await page.evaluate(()=>window.__PELAGIC__.diagnostics.camera);
  assert.ok(Math.hypot(...reset.map((v,i)=>v-[58,24,75][i]))<.01,'重置后镜头应回到默认位置并清除惯性');
  await page.locator('#tour').click();assert.equal(await page.locator('#tour').getAttribute('aria-pressed'),'true');
  await page.locator('#tour').click();
  await page.mouse.move(720,400);await page.mouse.wheel(0,-150);
  await page.waitForTimeout(500);
  assert.notDeepEqual(reset,await page.evaluate(()=>window.__PELAGIC__.diagnostics.camera));
  await page.locator('#reset').click();
  await page.locator('[data-weather="storm"]').click();
  await page.waitForFunction(()=>window.__PELAGIC__.state.storm>.9,{timeout:90000});
  await page.screenshot({path:path.join(dir,'02-storm.png')});
  assert.equal(await page.locator('[data-weather="storm"]').getAttribute('aria-pressed'),'true');
  await page.locator('[data-weather="night"]').click();
  await page.waitForFunction(()=>window.__PELAGIC__.state.hour>21.95&&window.__PELAGIC__.state.storm<.1,{timeout:90000});
  await page.screenshot({path:path.join(dir,'03-night.png')});
  await page.locator('#pause').click();
  const paused=await page.evaluate(()=>window.__PELAGIC__.diagnostics.time);
  await page.waitForTimeout(1000);
  assert.equal(await page.evaluate(()=>window.__PELAGIC__.diagnostics.time),paused);
  await page.locator('#pause').click();
  await page.locator('#quality').selectOption('low');
  await page.locator('#waves').fill('1.3');
  await page.waitForFunction(()=>window.__PELAGIC__.state.waves>1.0,{timeout:60000});
  await page.locator('#time').fill('12');
  assert.equal(await page.evaluate(()=>window.__PELAGIC__.state.hour),12);
  const downloadPromise=page.waitForEvent('download');await page.locator('#capture').click();
  const download=await downloadPromise;await download.saveAs(path.join(dir,'capture.png'));
  await page.locator('#collapse').click();assert.equal(await page.locator('#panel-content').isVisible(),false);
  await page.locator('#collapse').click();
  await page.locator('#hide').click();assert.equal(await page.locator('#interface').isVisible(),false);
  await page.locator('#restore-ui').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-weather="clear"]').click();
  await page.waitForFunction(()=>Math.abs(window.__PELAGIC__.state.hour-17.65)<.1,{timeout:90000});
  await page.screenshot({path:path.join(dir,'04-mobile.png')});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert.equal(overflow,false);
  const external=network.filter(url=>!url.startsWith(origin)&&!url.startsWith(origin.replace('http:','ws:'))&&!url.startsWith('data:')&&!url.startsWith('blob:'));
  assert.deepEqual(external,[],'场景不应请求外部素材');
  assert.deepEqual(errors,[],'浏览器控制台不应有错误');
  const report={ok:true,errors,externalRequests:external,diagnostics:await page.evaluate(()=>window.__PELAGIC__.diagnostics),note:'Headless Chrome SwiftShader 验证功能与着色器，不代表真实显卡帧率。'};
  await writeFile(path.join(dir,'browser-report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
